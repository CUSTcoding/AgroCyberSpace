const leadingEmoji = /^([\p{Extended_Pictographic}\p{Regional_Indicator}\p{Emoji_Modifier}\uFE0F\u200D]+)\s*(.*)$/u

export function Icon({ name, className }: { name: string; className?: string }) {
  const Component = icons[name] ?? CircleHelp
  return <Component className={className ? `ui-icon ${className}` : 'ui-icon'} aria-hidden="true" />
}

export function IconLabel({ text }: { text: string }) {
  const match = leadingEmoji.exec(text)
  if (!match) return <>{text}</>
  return (
    <>
      <Icon name={match[1]} />
      {match[2] && <span>{match[2]}</span>}
    </>
  )
}
