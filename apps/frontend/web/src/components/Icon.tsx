const leadingIcon = /^([a-z][a-z0-9-]*)\s+(.*)$/u

export function Icon({ name, className }: { name: string; className?: string }) {
  const Component = icons[name] ?? CircleHelp
  const iconClassName = ['ui-icon', `ui-icon-${name}`, className].filter(Boolean).join(' ')
  return <Component className={iconClassName} aria-hidden="true" />
}

export function IconLabel({ text }: { text: string }) {
  const match = leadingIcon.exec(text)
  if (!match || !icons[match[1]]) return <>{text}</>
  return (
    <>
      <Icon name={match[1]} />
      {match[2] && <span>{match[2]}</span>}
    </>
  )
}
